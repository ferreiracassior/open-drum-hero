import type { ChartNote, DrumTrack, Lane, SongPackage } from './protocol';
import { t } from './i18n';
import { LANES } from './protocol';

/**
 * Builds the game chart from a Guitar Pro file (any version alphaTab reads:
 * .gp3/.gp4/.gp5/.gpx/.gp). Runs on the device itself — the same in the exe (Electron) and the apk (Android).
 *
 * - alphaTab generates the score's MIDI (repeats, voltas and tempo changes already unrolled).
 *   That MIDI is stored with the song and the "Synthetic" sound comes from it.
 * - The chart notes come from the score itself, bar by bar IN PLAYED ORDER (same ticks as the
 *   MIDI), so chart and sound match exactly; accent, ghost note and half-open hi-hat come from the
 *   score markings.
 */

export const PPQ = 960;   // ticks per quarter note of the MIDI generated by alphaTab

/** General MIDI note → (lane, articulation). The same map the old importer used. */
export const GM_TO_LANE: Record<number, [Lane, string]> = {
  35: ['kick', 'hit'], 36: ['kick', 'hit'],
  37: ['snare', 'side_stick'], 38: ['snare', 'hit'], 39: ['snare', 'clap'], 40: ['snare', 'hit'],
  42: ['hihat', 'closed'], 44: ['hihat', 'pedal'], 46: ['hihat', 'open'],
  88: ['hihat', 'half'],   // Songsterr used to export half-open as 88 (outside GM)
  48: ['tom1', 'hit'], 50: ['tom1', 'hit'],
  45: ['tom2', 'hit'], 47: ['tom2', 'hit'],
  41: ['floor', 'hit'], 43: ['floor', 'hit'],
  49: ['crash', 'crash'], 57: ['crash2', 'crash'], 52: ['crash', 'china'], 55: ['crash', 'splash'],
  51: ['ride', 'ride'], 59: ['ride', 'ride'], 53: ['ride', 'bell'],
};

/** GP7 articulations that aren't the GM number itself (alphaTab/Guitar Pro 7 default list). */
const GP7_ARTICULATION_TO_GM: Record<number, number> = {
  29: 51, 30: 49, 31: 37, 33: 37, 91: 38, 92: 46, 93: 51, 94: 51, 95: 55, 96: 52, 97: 49, 98: 57,
  114: 36, 115: 49, 116: 49, 126: 51, 127: 53,
};
const HIHAT_HALF_ARTICULATION = 92;

export interface BuiltSong {
  pkg: SongPackage;
  /** MIDI generated from the score (the song's source.mid file; the synthetic sound comes from it). */
  mid: Uint8Array;
}

export interface BuildOptions {
  id?: string;
  title?: string;
  artist?: string;
}

type AlphaTab = typeof import('@coderline/alphatab');

export async function buildSongFromGp(gp: Uint8Array, opts: BuildOptions = {}): Promise<BuiltSong> {
  const at: AlphaTab = await import('@coderline/alphatab');
  const settings = new at.Settings();
  let score;
  try {
    score = at.importer.ScoreLoader.loadScoreFromBytes(gp, settings);
  } catch {
    throw new Error(t('err.notGuitarPro'));
  }
  const warnings: string[] = [];

  // score MIDI + map of the bars in played order
  const midi = new at.midi.MidiFile();
  midi.format = at.midi.MidiFileFormat.MultiTrack;
  const generator = new at.midi.MidiFileGenerator(score, settings, new at.midi.AlphaSynthMidiFileHandler(midi, true));
  generator.generate();
  const played = generator.tickLookup.masterBars;
  if (!played.length) throw new Error(t('err.emptyScore'));

  // (midi.events has a bug in alphaTab 1.8 with several tracks — infinite recursion; read track by track)
  const tempo = new TempoMap(midi.tracks.flatMap(t => t.events)
    .filter(e => e.type === at.midi.MidiEventType.TempoChange)
    .map(e => [e.tick, (e as InstanceType<AlphaTab['midi']['TempoChangeEvent']>).microSecondsPerQuarterNote] as [number, number]));

  // drums: percussion tracks
  const drumTracks: DrumTrack[] = [];
  const unknown = new Map<number, number>();
  for (const track of score.tracks) {
    const staff = track.staves.find(s => s.isPercussion);
    if (!staff) continue;
    const arts = track.percussionArticulations;
    const notes: ChartNote[] = [];
    for (const mbl of played) {
      const bar = staff.bars[mbl.masterBar.index];
      if (!bar) continue;
      for (const voice of bar.voices) {
        for (const beat of voice.beats) {
          if (beat.isRest) continue;
          const tick = mbl.start + beat.playbackStart;
          const velocity = 15 + 16 * (beat.dynamics as number);
          for (const note of beat.notes) {
            if (note.isTieDestination) continue;
            const idx = note.percussionArticulation;
            const art = idx >= 0 && idx < arts.length ? arts[idx] : null;
            const gm = art ? art.outputMidiNumber : GP7_ARTICULATION_TO_GM[idx] ?? idx;
            const isHalf = art ? art.id === HIHAT_HALF_ARTICULATION : idx === HIHAT_HALF_ARTICULATION;
            const cls = GM_TO_LANE[gm];
            if (!cls) { unknown.set(gm, (unknown.get(gm) ?? 0) + 1); continue; }
            const [lane, kind] = cls;
            notes.push({
              t: round3(tempo.ms(tick)), tick, n: gm, lane,
              art: lane === 'hihat' && isHalf ? 'half' : kind,
              v: Math.min(127, Math.max(1, velocity)),
              acc: (note.accentuated as number) > 0,
              ghost: note.isGhost,
            });
          }
        }
      }
    }
    notes.sort((a, b) => a.tick - b.tick || a.n - b.n);
    if (notes.length) drumTracks.push({ name: track.name || 'Bateria', midiTrack: track.index, channel: 9, notes });
  }
  for (const [gm, n] of unknown) warnings.push(t('warn.unknownPiece', { gm, n }));
  if (!drumTracks.length) throw new Error(t('err.noDrumTrack'));
  drumTracks.sort((a, b) => b.notes.length - a.notes.length);

  // bars, beats, sections and lyrics (in played order)
  const measures = played.map((mbl, index) => ({
    index, ms: round3(tempo.ms(mbl.start)),
    num: mbl.masterBar.timeSignatureNumerator, den: mbl.masterBar.timeSignatureDenominator,
  }));
  const beats: { ms: number; downbeat: boolean }[] = [];
  played.forEach(mbl => {
    const num = Math.max(1, mbl.masterBar.timeSignatureNumerator);
    const step = (mbl.end - mbl.start) / num;
    for (let b = 0; b < num; b++) beats.push({ ms: round3(tempo.ms(mbl.start + b * step)), downbeat: b === 0 });
  });
  const sections: { name: string; measure: number; ms: number }[] = [];
  played.forEach((mbl, i) => {
    const name = mbl.masterBar.section?.text?.trim() || mbl.masterBar.section?.marker?.trim();
    if (name) sections.push({ name, measure: i, ms: measures[i].ms });
  });
  const lyrics: { t: number; text: string }[] = [];
  const lyricTrack = score.tracks.find(t => t.staves.some(s => s.bars.some(b => b.voices.some(v => v.beats.some(x => x.lyrics?.some(l => !!l))))));
  if (lyricTrack) {
    const staff = lyricTrack.staves[0];
    const sylOf = lyricsSkippingTies(staff);
    for (const mbl of played) {
      for (const beat of staff.bars[mbl.masterBar.index]?.voices[0]?.beats ?? []) {
        const text = sylOf.get(beat);
        if (text) lyrics.push({ t: round3(tempo.ms(mbl.start + beat.playbackStart)), text });
      }
    }
    lyrics.sort((a, b) => a.t - b.t);
  }

  const title = (opts.title ?? score.title ?? '').trim() || t('common.untitled');
  const artist = (opts.artist ?? score.artist ?? '').trim();
  const last = played[played.length - 1];
  const pkg: SongPackage = {
    version: 1,
    id: opts.id ?? slugify(`${artist}-${title}`),
    title, artist,
    durationMs: round3(tempo.ms(last.end)),
    ppq: PPQ,
    tempoMap: tempo.json(),
    measures, beats, sections,
    drumTracks,
    audio: { youtube: [], synth: { file: 'source.mid', offsetMs: 0 } },
    lyrics, lyricsV: LYRICS_VERSION,
    warnings,
  };
  (pkg as SongPackage & { lanes: Lane[] }).lanes = LANES;
  return { pkg, mid: midi.toBinary() };
}

/** Converts ticks to milliseconds honoring tempo changes. */
export class TempoMap {
  private pts: { tick: number; us: number; ms: number }[] = [];

  constructor(changes: [number, number][], private ppq = PPQ) {
    const byTick = new Map<number, number>([[0, 500_000]]);
    for (const [tick, us] of [...changes].sort((a, b) => a[0] - b[0])) if (us > 0) byTick.set(tick, us);
    let ms = 0, prev: { tick: number; us: number } | null = null;
    for (const [tick, us] of [...byTick].sort((a, b) => a[0] - b[0])) {
      if (prev) ms += ((tick - prev.tick) * prev.us) / this.ppq / 1000;
      this.pts.push({ tick, us, ms });
      prev = { tick, us };
    }
  }

  ms(tick: number): number {
    let lo = 0, hi = this.pts.length - 1;
    while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (this.pts[mid].tick <= tick) lo = mid; else hi = mid - 1; }
    const p = this.pts[lo];
    return p.ms + ((tick - p.tick) * p.us) / this.ppq / 1000;
  }

  json(): { tick: number; ms: number; bpm: number }[] {
    return this.pts.map(p => ({ tick: p.tick, ms: round3(p.ms), bpm: Math.round((60_000_000 / p.us) * 10000) / 10000 }));
  }
}

export function slugify(text: string): string {
  const s = text.normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase();
  return s || 'musica';
}

function round3(v: number): number {
  return Math.round(v * 1000) / 1000;
}

/** Version of the syllable distribution (songs imported earlier are fixed when opened). */
export const LYRICS_VERSION = 2;

type AtBeat = { isEmpty: boolean; isRest: boolean; lyrics: string[] | null; notes: { isTieDestination: boolean }[] };

/**
 * Syllable of each lyric beat. alphaTab puts a syllable on every note, including the continuation of
 * a tied note, and counts empty entries in the text as notes; Guitar Pro (and Songsterr) don't.
 * Because of that each tie pushed the lyrics one note early and the karaoke kept "speeding up" through the song.
 * Here the syllables alphaTab distributed are read in order and redistributed one per played note,
 * skipping tied notes. (Checked on Songsterr's Stairway to Heaven and Have You Ever Seen the Rain:
 * every syllable lands on the right melody note.)
 */
function lyricsSkippingTies(staff: { bars: { voices: { beats: AtBeat[] }[] }[] }): Map<AtBeat, string> {
  const beats = staff.bars.flatMap(b => b.voices[0]?.beats ?? []).filter(b => !b.isEmpty && !b.isRest);
  const lines = Math.max(0, ...beats.map(b => b.lyrics?.length ?? 0));
  const out = new Map<AtBeat, string>();
  for (let li = 0; li < lines; li++) {
    const seq = beats.map(b => b.lyrics?.[li] ?? '');
    const start = seq.findIndex(x => !!x.trim());
    if (start < 0) continue;
    let end = seq.length;
    while (end > start && !seq[end - 1].trim()) end--;
    // empty entries (double space, line break in the text) don't take a note in Guitar Pro
    const chunks = seq.slice(start, end).map(x => x.trim()).filter(x => !!x);
    let ci = 0;
    for (let bi = start; bi < beats.length && ci < chunks.length; bi++) {
      const b = beats[bi];
      if (b.notes.length && b.notes.every(n => n.isTieDestination)) continue;   // continuation of a tied note
      const text = chunks[ci++];
      if (!out.has(b)) out.set(b, text);
    }
  }
  return out;
}
